"""Write the HISS standard as Markdown straight from the catalogue files.

Text and data never diverge because the document has no content of its own beyond fixed framing sentences:
every control, mapping and obligation line is read from the catalogue. Run it alone with

    python src/render_standard.py [catalogue folder] [output file]
"""
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catalogue import FRAMEWORK_NAMES, FRAMEWORKS, load_catalogue, load_domain_names, ordered_domains  # noqa: E402
from common import AUTHOR, DOCS_DIR, domain_sort_key, resolve_path, write_text  # noqa: E402

STRENGTH_PHRASE = {"D": "Maps to", "P": "Maps in part to", "J": "Judged to relate to"}
DEFAULT_OUT = os.path.join(DOCS_DIR, "HISS_Standard_v1.md")


def join_and(items):
    """A, B and C with no serial comma."""
    items = [str(i) for i in items if str(i) != ""]
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    return ", ".join(items[:-1]) + " and " + items[-1]


def cell(text):
    return str(text).replace("|", "/").replace("\n", " ").strip()


def _target_text(x):
    t = x["target_id"] + (" " + x["target_title"] if x.get("target_title") else "")
    return t


def mapping_lines(control_id, crosswalk_by_control):
    """One line per framework with the strength wording rules applied."""
    rows = crosswalk_by_control.get(control_id, [])
    by_fw = defaultdict(list)
    for x in rows:
        by_fw[x["framework"]].append(x)
    lines = []
    for fw in FRAMEWORKS:
        if fw not in by_fw:
            continue
        parts = []
        for s in ("D", "P", "J"):
            hits = [x for x in by_fw[fw] if x["strength"] == s and x["target_status"] == "VERIFIED"]
            if hits:
                txt = "%s %s" % (STRENGTH_PHRASE[s], join_and(_target_text(x) for x in hits))
                if s == "D":
                    srcs = sorted({x["source"] for x in hits if x.get("source")})
                    if srcs:
                        txt += " (source: %s)" % join_and(srcs)
                parts.append(txt + ".")
        sec = [x for x in by_fw[fw] if x["target_status"] == "SECONDARY"]
        if sec:
            parts.append("Reported by a secondary source, not confirmed: %s." % join_and(
                "%s (%s)" % (_target_text(x), x["strength"]) for x in sec))
        nv = [x for x in by_fw[fw] if x["target_status"] == "NOT VERIFIED"]
        if nv:
            parts.append("Target not verified and not scored: %s." % join_and(_target_text(x) for x in nv))
        lines.append("- %s. %s" % (FRAMEWORK_NAMES.get(fw, fw), " ".join(parts)))
    return lines


def obligation_lines(control_id, obligations):
    out = []
    for o in obligations:
        if control_id in o["control_list"]:
            if o["status"] == "VERIFIED":
                out.append("- %s (%s): %s, %s." % (o["obligation_id"], o["jurisdiction"], o["instrument"], o["provision"]))
            else:
                out.append("- %s (%s): tracking only. Reported by a secondary source (%s): %s, %s." % (
                    o["obligation_id"], o["jurisdiction"], o.get("fact_ref", ""), o["instrument"], o["provision"]))
    return out


def render_standard(cat, domain_names=None):
    """Return the standard as one Markdown string."""
    domain_names = domain_names if domain_names is not None else load_domain_names(cat)
    controls = cat["controls"]
    realities = {r["reality_id"]: r for r in cat["realities"]}
    profiles = cat["profiles"].get("profiles", {})
    triggers = cat["profiles"].get("triggers", {})
    models = cat["profiles"].get("operating_models", ["owned", "managed", "franchised"])
    xw = defaultdict(list)
    for x in cat["crosswalk"]:
        xw[x["control_id"]].append(x)
    domains = ordered_domains(controls)
    n_base = sum(1 for c in controls if c["level"] == "Baseline")
    n_enh = sum(1 for c in controls if c["level"] == "Enhanced")

    L = []
    a = L.append
    a("# HISS Standard v1")
    a("")
    a("Hospitality Information Security Standard for hotels. Author: %s." % AUTHOR)
    a("")
    a("This file is generated by render_standard.py from the catalogue files. To change the text edit the catalogue and run the tool again.")
    a("")
    a("The catalogue holds %d controls in %d domains: %d Baseline and %d Enhanced." % (
        len(controls), len(domains), n_base, n_enh))
    a("")
    a("## 1 Scope and use")
    a("")
    a("HISS is written to sit on top of an ISO/IEC 27001 information security management system and does not replace it. "
      "It is a self assessment framework and not a certification scheme. Obligation entries summarise legal duties as they "
      "appear in the fact files and are not legal advice. Standards text is paraphrased: identifiers and short titles are used "
      "and control wording from ISO or PCI documents is not reproduced.")
    a("")
    a("## 2 Profiles, requirement levels and triggers")
    a("")
    a("Profile thresholds are the author's judgement. Baseline controls apply to every profile. Enhanced controls apply to "
      "the profiles listed on the control. An Enhanced control that does not list the profile becomes mandatory when one of "
      "its triggers is active.")
    a("")
    a("| Profile | Name | Description |")
    a("|---|---|---|")
    for key in ("S", "M", "G"):
        p = profiles.get(key, {})
        a("| %s | %s | %s |" % (key, cell(p.get("name", "")), cell(p.get("description", ""))))
    a("")
    a("| Trigger | Meaning |")
    a("|---|---|")
    for key in sorted(triggers):
        a("| %s | %s |" % (key, cell(triggers[key])))
    a("")
    a("Operating models: %s. Each control names the accountable party for each model as group, property, vendor or franchisee." % join_and(models))
    a("")
    a("## 3 Hotel realities")
    a("")
    a("| Id | Reality | Description |")
    a("|---|---|---|")
    for r in cat["realities"]:
        a("| %s | %s | %s |" % (r["reality_id"], cell(r["name"]), cell(r["description"])))
    a("")
    a("## 4 Maturity scale")
    a("")
    a("| Score | Meaning |")
    a("|---|---|")
    for s, m in ((0, "Not in place"), (1, "Ad hoc"), (2, "Documented"), (3, "Implemented with evidence"),
                 (4, "Measured and reviewed")):
        a("| %d | %s |" % (s, m))
    a("")
    a("A control counts as met at 3 or above. The scale is the study's own and is only loosely aligned to the NIST CSF tiers.")
    a("")
    a("## 5 Mapping strength")
    a("")
    a("Each crosswalk row carries a strength label. D (direct) means the objectives match, the target is verified and a named "
      "source supports the link. The text then says maps to. P (partial) means the target covers part of the control or "
      "the control covers part of the target. The text then says maps in part to. J (judgement) is the author's reading with no "
      "source support. The text then says judged to relate to.")
    a("")
    a("## 6 Domains and controls")
    a("")
    for d in domains:
        a("### %s %s" % (d, domain_names.get(d, "")) if domain_names.get(d) else "### %s" % d)
        a("")
        for c in sorted([c for c in controls if c["domain"] == d], key=lambda c: c["control_id"]):
            a("#### %s %s" % (c["control_id"], c["title"]))
            a("")
            a("Level: %s. Profiles: %s. Triggers: %s." % (c["level"], join_and(c["profile_list"]),
                                                       join_and(c["trigger_list"]) or "none"))
            a("")
            a("Accountable by operating model: owned %s, managed %s, franchised %s." % (
                c["owner_owned"], c["owner_managed"], c["owner_franchised"]))
            a("")
            a("Objective: %s" % c["objective"])
            a("")
            a("Requirement: %s" % c["requirement"])
            a("")
            a("Hotel rationale: %s" % c["rationale"])
            a("")
            a("Realities addressed: %s." % join_and("%s %s" % (r, realities[r]["name"]) if r in realities else r
                                                  for r in c["reality_list"]))
            a("")
            a("Evidence expected: %s." % join_and(c["evidence_list"]))
            a("")
            a("Assessment question: %s" % c["assessment_question"])
            a("")
            a("Capstone 1 link: %s. Basis: %s." % (c["c1_link"], c["basis"]))
            a("")
            ml = mapping_lines(c["control_id"], xw)
            if ml:
                a("Crosswalk:")
                a("")
                L.extend(ml)
                a("")
            ol = obligation_lines(c["control_id"], cat["obligations"])
            if ol:
                a("Linked obligations:")
                a("")
                L.extend(ol)
                a("")
    a("## 7 Control index")
    a("")
    a("| Control | Title | Level | Profiles | Triggers |")
    a("|---|---|---|---|---|")
    for c in sorted(controls, key=lambda c: (domain_sort_key(c["domain"]), c["control_id"])):
        a("| %s | %s | %s | %s | %s |" % (c["control_id"], cell(c["title"]), c["level"], "; ".join(c["profile_list"]),
                                            "; ".join(c["trigger_list"])))
    a("")
    a("## 8 Obligations register")
    a("")
    a("| Obligation | Jurisdiction | Instrument | Provision | Status | Controls |")
    a("|---|---|---|---|---|---|")
    for o in cat["obligations"]:
        a("| %s | %s | %s | %s | %s | %s |" % (o["obligation_id"], o["jurisdiction"], cell(o["instrument"]),
                                                cell(o["provision"]), o["status"], "; ".join(o["control_list"])))
    a("")
    return "\n".join(L)


def write_standard(cat, path=None, domain_names=None):
    path = path or DEFAULT_OUT
    write_text(path, render_standard(cat, domain_names))
    return path


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    cat = load_catalogue(argv[0] if argv else None)
    out = resolve_path(argv[1]) if len(argv) > 1 else DEFAULT_OUT
    print("Wrote", write_standard(cat, out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
